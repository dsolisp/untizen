using System;
using System.Collections.Generic;
using System.IO;
using System.Text.Json;

public sealed class LibraryApp
{
 public string Name {get;set;}
 public string Id {get;set;}
 public string Asset {get;set;}
 public string Description {get;set;}
 public string Fit {get;set;}="cover";
 public string Background {get;set;}="#FFFFFF";
 public int Width {get;set;}
 public int Height {get;set;}
 public float[] Crop {get;set;}
 public bool Utility {get;set;}
}

public static class AppLibrary
{
 public const int Columns=5, Rows=3, PageSize=Columns*Rows;
 public static List<LibraryApp> Load(string path)
 {
  var apps=JsonSerializer.Deserialize<List<LibraryApp>>(File.ReadAllText(path));
  if(apps==null||apps.Count==0)throw new InvalidDataException("App library is empty.");
  var ids=new HashSet<string>();
  foreach(var app in apps)
  {
   if(string.IsNullOrWhiteSpace(app.Name)||string.IsNullOrWhiteSpace(app.Id)||!ids.Add(app.Id)
      ||string.IsNullOrWhiteSpace(app.Asset)||Path.IsPathRooted(app.Asset)||app.Asset.Contains("..")
      ||app.Width<=0||app.Height<=0)
   throw new InvalidDataException("Invalid app library entry.");
   var crop=app.Crop;
   if(crop!=null&&(crop.Length!=4||!Array.TrueForAll(crop,float.IsFinite)
      ||crop[0]<0||crop[1]<0||crop[2]<=0||crop[3]<=0
      ||crop[0]+crop[2]>1||crop[1]+crop[3]>1))
    throw new InvalidDataException("Invalid artwork crop.");
  }
  return apps;
 }
 public static int PageCount(int count)=>(count+PageSize-1)/PageSize;
 public static int VisibleCount(int count,int page)=>Math.Max(0,Math.Min(PageSize,count-page*PageSize));
 // Return an absolute catalog index. -1 moves focus to the navigation tabs.
 public static int Move(int count,int absolute,string key)
 {
  if(count<=0)return -1;
  absolute=Math.Clamp(absolute,0,count-1);
  int page=absolute/PageSize,local=absolute%PageSize,col=local%Columns,row=local/Columns;
  int pageStart=page*PageSize,visible=VisibleCount(count,page);
  if(key=="Left")return Math.Max(0,absolute-1);
  if(key=="Right")return Math.Min(count-1,absolute+1);
  if(key=="Up")
  {
   if(row>0)return absolute-Columns;
   if(page==0)return -1;
   return pageStart-Columns+col;
  }
  if(key=="Down")
  {
   if((row+1)*Columns<visible)return pageStart+Math.Min(local+Columns,visible-1);
   int next=pageStart+PageSize;
   return next<count?Math.Min(next+col,count-1):absolute;
  }
  return absolute;
 }
}

// Every app the TV reports as installed, generated by `tv.py catalog` at deploy
// time. The file is optional: without it the launcher shows the curated menu
// exactly as before. Ceiling: apps installed after the last catalog run stay
// invisible until it runs again; the upgrade path is reading the package
// registry from the launcher itself once its permissions are confirmed.
public static class InstalledCatalog
{
 public const string DefaultAsset="installed-tile.svg";
 public const string DefaultBackground="#23252c";
 public static List<LibraryApp> Load(string path)
 {
  var apps=new List<LibraryApp>();
  if(string.IsNullOrEmpty(path)||!File.Exists(path))return apps;
  using var doc=JsonDocument.Parse(File.ReadAllText(path));
  if(doc.RootElement.ValueKind!=JsonValueKind.Array)return apps;
  var ids=new HashSet<string>();
  foreach(var item in doc.RootElement.EnumerateArray())
  {
   if(item.ValueKind!=JsonValueKind.Object)continue;
   string id=Str(item,"Id");
   if(string.IsNullOrWhiteSpace(id)||!ids.Add(id))continue;
   string name=Str(item,"Name");
   if(string.IsNullOrWhiteSpace(name))name=id;
   string asset=Str(item,"Asset");
   if(string.IsNullOrWhiteSpace(asset)||Path.IsPathRooted(asset)||asset.Contains(".."))asset=DefaultAsset;
   string background=Str(item,"Background");
   if(string.IsNullOrWhiteSpace(background))background=DefaultBackground;
   apps.Add(new LibraryApp{Id=id,Name=name,Asset=asset,Background=background,Fit="none",Description="Installed app"});
  }
  return apps;
 }
 static string Str(JsonElement item,string name)
 {
  return item.TryGetProperty(name,out var value)&&value.ValueKind==JsonValueKind.String?value.GetString():"";
 }
}

// Two lists over one installed catalog: "Your Apps" (the menu the household
// keeps visible) and "All Apps" (everything installed). Hiding an app moves it
// out of the menu without uninstalling anything; the choice persists in
// /var/tmp next to the theme and the recents journal.
public static class MenuCatalog
{
 public static List<LibraryApp> Visible(List<LibraryApp> curated,List<LibraryApp> installed,List<string> hidden)
 {
  var visible=new List<LibraryApp>();
  bool filter=installed!=null&&installed.Count>0;
  var installedIds=new HashSet<string>();
  if(filter)foreach(var app in installed)installedIds.Add(app.Id);
  foreach(var app in curated??new List<LibraryApp>())
  {
   if(app.Utility){visible.Add(app);continue;}
   if(hidden!=null&&hidden.Contains(app.Id))continue;
   if(filter&&!installedIds.Contains(app.Id))continue;
   visible.Add(app);
  }
  if(filter)
  {
   var curatedIds=new HashSet<string>();
   foreach(var app in curated??new List<LibraryApp>())curatedIds.Add(app.Id);
   var extra=installed.FindAll(a=>!curatedIds.Contains(a.Id)&&(hidden==null||!hidden.Contains(a.Id)));
   extra.Sort((x,y)=>string.Compare(x.Name,y.Name,StringComparison.OrdinalIgnoreCase));
   visible.AddRange(extra);
  }
  return visible;
 }
 // The All Apps list: every installed app, curated artwork when it exists,
 // sorted by name. Utility tiles are launcher furniture and never listed.
 public static List<LibraryApp> All(List<LibraryApp> installed,List<LibraryApp> curated)
 {
  var all=new List<LibraryApp>();
  foreach(var app in installed??new List<LibraryApp>())
  {
   var art=curated==null?null:curated.Find(c=>c.Id==app.Id);
   if(art!=null&&art.Utility)continue;
   all.Add(art??app);
  }
  all.Sort((x,y)=>string.Compare(x.Name,y.Name,StringComparison.OrdinalIgnoreCase));
  return all;
 }
 public static List<string> Toggle(List<string> hidden,string id)
 {
  var next=new List<string>();
  foreach(var entry in hidden??new List<string>())if(entry!=id&&!next.Contains(entry))next.Add(entry);
  if(next.Count==(hidden??new List<string>()).Count)next.Add(id);
  next.Sort(StringComparer.OrdinalIgnoreCase);
  return next;
 }
}

public static class MenuState
{
 public static List<string> Load(string path)
 {
  try{
   var loaded=JsonSerializer.Deserialize<List<string>>(File.ReadAllText(path));
   var hidden=new List<string>();
   if(loaded!=null)foreach(var id in loaded)if(!string.IsNullOrWhiteSpace(id)&&!hidden.Contains(id))hidden.Add(id);
   return hidden;
  }catch{return new List<string>();}
 }
 public static void Save(string path,List<string> hidden)
 {
  try{File.WriteAllText(path,JsonSerializer.Serialize(hidden??new List<string>()));}catch{}
 }
}
